<?php

namespace RH\AdminUtils;

/**
 * Various handy WP CLI commands
 */
class WpCliCommands
{
    /**
     * Static init function instead of a constructor
     */
    public static function init()
    {
        if (!rhau()->is_wp_cli()) {
            return;
        }
        \WP_CLI::add_command('rhau do-action-save-post', [__CLASS__, 'wp_cli_do_action_save_post']);
        \WP_CLI::add_command('rhau test-imagick', [__CLASS__, 'wp_cli_test_imagick']);
    }

    /**
     * Tests which formats Imagick can actually encode. WP's supports_mime_type() also reports decode-only formats
     *
     * ## EXAMPLES
     *
     *     wp rhau test-imagick
     */
    public static function wp_cli_test_imagick(): void
    {
        \WP_CLI::log('SAPI: ' . PHP_SAPI);
        \WP_CLI::log('php.ini: ' . (php_ini_loaded_file() ?: 'none'));

        require_once ABSPATH . WPINC . '/class-wp-image-editor.php';
        require_once ABSPATH . WPINC . '/class-wp-image-editor-imagick.php';
        if (!\WP_Image_Editor_Imagick::test()) {
            \WP_CLI::error('WP can\'t use Imagick (extension missing, outdated or lacking required methods)');
        }

        \WP_CLI::log('Imagick: ' . phpversion('imagick'));
        \WP_CLI::log(\Imagick::getVersion()['versionString']);

        $mime_types = ['image/jpeg', 'image/png', 'image/gif', 'image/webp', 'image/avif'];
        $generated = array_unique(array_map(
            fn ($mime_type) => wp_get_image_editor_output_format('', $mime_type)[$mime_type] ?? $mime_type,
            $mime_types
        ));

        $rows = array_map(function ($mime_type) use ($generated) {
            $bytes = self::get_imagick_probe_bytes(wp_get_default_extension_for_mime_type($mime_type));
            return [
                'format' => $mime_type,
                'supported per WP' => \WP_Image_Editor_Imagick::supports_mime_type($mime_type) ? 'yes' : 'no',
                'probe bytes' => $bytes,
                'generated by WP' => in_array($mime_type, $generated, true) ? 'yes' : 'no',
                'ok' => $bytes > 0 ? 'yes' : 'no',
            ];
        }, $mime_types);

        \WP_CLI\Utils\format_items('table', $rows, array_keys($rows[0]));

        $failed = array_column(array_filter(
            $rows,
            fn ($row) => $row['generated by WP'] === 'yes' && $row['ok'] === 'no'
        ), 'format');
        if ($failed) {
            \WP_CLI::error('Imagick can\'t encode: ' . implode(', ', $failed));
        }

        \WP_CLI::success('Imagick can encode all formats WP generates');
    }

    /**
     * Encodes an 8x8 image, returns the byte count (0 = can't encode)
     */
    private static function get_imagick_probe_bytes(string $extension): int
    {
        try {
            $image = new \Imagick();
            $image->newImage(8, 8, 'red');
            $image->setImageFormat($extension);
            return strlen($image->getImageBlob());
        } catch (\Throwable) {
            return 0;
        }
    }

    /**
     * Runs the `save_post` action on posts
     *
     * ## OPTIONS
     *
     * [--type=<string>]
     * : A comma-separated list of post types to be processed
     */
    public static function wp_cli_do_action_save_post(array $args = [], array $assoc_args = []): void
    {
        $post_type = $assoc_args['type'] ?? null;
        if (!$post_type) {
            \WP_CLI::error("Please provide a post type");
        }
        if (!post_type_exists($post_type)) {
            \WP_CLI::error("Post type $post_type does not exist");
        }
        $posts = get_posts([
            'post_type' => $post_type,
            'posts_per_page' => -1,
            'post_status' => 'any',
        ]);
        $count = count($posts);
        $pt_object = get_post_type_object($post_type);
        \WP_CLI::log("Processing $count posts from {$pt_object->labels->name}");

        foreach ($posts as $post) {
            do_action('save_post', $post->ID, $post, true);
        }
    }
}
